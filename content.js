/* 以下は表示プログラムです。通常は変更不要です。 */
function getValue(path) {return path.split('.').reduce((obj,key)=>obj?.[key], SITE_CONTENT);}
function renderContent() {
  document.querySelectorAll('[data-content]').forEach(el => {
    const value=getValue(el.dataset.content);
    if (value == null) return;
    if (el.tagName==='META') el.setAttribute('content',String(value));
    else if (el.tagName==='TITLE') el.textContent=String(value);
    else el.textContent=String(value);
  });
  document.querySelectorAll('[data-nav]').forEach(a => {
    const val=SITE_CONTENT.navigation[a.dataset.nav];
    if (!val) return;
    const small=a.querySelector('small');
    a.replaceChildren(document.createTextNode(val.en),small);
    if(small)small.textContent=val.ja;
  });
}
function safeText(x) {return String(x??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));}
function renderList(id, items, renderer, emptyText) {
 const el=document.getElementById(id);if(!el)return;
 el.innerHTML=items.length?items.map(renderer).join(''):`<p class="empty">${emptyText}</p>`;
}
